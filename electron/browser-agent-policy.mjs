export const AGENT_ACTIONS = ['browse', 'download', 'upload'];
export const DEFAULT_AGENT_POLICY = { browse: 'allow', download: 'ask', upload: 'ask' };
export function agentSiteOrigin(value) {
  const url = new URL(value);
  if (!['https:', 'http:'].includes(url.protocol) || url.username || url.password) throw new Error('Enter an http or https website without credentials');
  if (url.pathname !== '/' || url.search || url.hash) throw new Error('Use a site origin, such as https://example.com');
  return url.origin;
}
export function cleanAgentRule(value) {
  if (!value || typeof value !== 'object') throw new Error('Choose site permissions');
  const rule = {};
  for (const action of AGENT_ACTIONS) {
    if (!['allow', 'ask', 'block'].includes(value[action])) throw new Error('Invalid site permission');
    rule[action] = value[action];
  }
  return rule;
}
export function agentPermission(rules, url, action) {
  if (!AGENT_ACTIONS.includes(action)) return 'block';
  if (rules !== undefined && (!rules || typeof rules !== 'object' || Array.isArray(rules))) return 'block';
  if (url === 'about:blank' && action === 'browse') return 'allow';
  try {
    const origin = new URL(url);
    if (!['https:', 'http:'].includes(origin.protocol) || origin.username || origin.password) return 'block';
    const rule = rules?.[origin.origin];
    const mode = rule === undefined ? DEFAULT_AGENT_POLICY[action] : rule?.[action];
    return ['allow', 'ask', 'block'].includes(mode) ? mode : 'block';
  } catch { return 'block'; }
}

const sameAgent = (current, captured) => current?.key === captured.key && current?.scope === captured.scope;
// Bot-check widgets (Cloudflare, hCaptcha, reCAPTCHA) post their own proof of
// a real browser, not the person's data. Gating them breaks the check.
export function isHumanCheckRequest(value) {
  try {
    const url = new URL(value); const host = url.hostname.toLowerCase();
    if (url.protocol !== 'https:') return false;
    if (host === 'challenges.cloudflare.com' || url.pathname.startsWith('/cdn-cgi/challenge-platform/')) return true;
    if (host === 'hcaptcha.com' || host.endsWith('.hcaptcha.com')) return true;
    return ['www.google.com', 'www.recaptcha.net', 'recaptcha.net'].includes(host) && url.pathname.startsWith('/recaptcha/');
  } catch { return false; }
}
export async function authorizeAgentNetwork(details, { guestFromId, agentForGuest, authorize, hasAgentControl = () => false }) {
  const guest = guestFromId(details.webContentsId);
  const agent = agentForGuest(details.webContentsId);
  if (!guest) return !(details.uploadData?.length && hasAgentControl());
  if (!agent) return true;
  const actions = [];
  if (details.resourceType === 'mainFrame') actions.push('browse');
  if (details.uploadData?.length && !(details.resourceType !== 'mainFrame' && isHumanCheckRequest(details.url))) actions.push('upload');
  try {
    for (const action of actions) {
      await authorize(agent.profileId, guest.id, details.url, action, action === 'upload' ? 'This includes files and form submissions to this site.' : 'Allow the bot to open this site?', agent.scope, { fullAccess: agent.fullAccess === true });
      if (guest.isDestroyed() || !sameAgent(agentForGuest(guest.id), agent)) return false;
    }
    return true;
  } catch { return false; }
}
export async function authorizeAgentDownload(guest, item, { agentForGuest, authorize }) {
  const agent = agentForGuest(guest.id);
  if (!agent) return false;
  const initiating = guest.getURL();
  try {
    const urls = [initiating, ...(item.getURLChain?.() ?? []), item.getURL()];
    const origins = new Set(urls.map(value => {
      const url = new URL(value);
      // A blob is generated by its creator site; opaque/data/file URLs do
      // not grant an unrelated origin's download permission.
      if (url.protocol === 'blob:' && url.origin === new URL(initiating).origin) return url.origin;
      if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password) throw new Error('Unsupported download origin');
      return url.origin;
    }));
    for (const url of origins) {
      await authorize(agent.profileId, guest.id, url, 'download', `Download ${String(item.getFilename()).slice(0, 500)}?`, agent.scope, { fullAccess: agent.fullAccess === true });
      if (guest.isDestroyed() || guest.getURL() !== initiating || !sameAgent(agentForGuest(guest.id), agent)) return false;
    }
    return true;
  } catch { return false; }
}
