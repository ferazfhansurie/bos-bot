import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, expect, it, vi } from "vitest";
let home = "";
afterEach(async () => { const { closeMessageDb } = await import("./message-db.ts"); closeMessageDb(); vi.unstubAllEnvs(); rmSync(home, { recursive: true, force: true }); });
it("persists execution aliases without creating user tasks or splitting room history", async () => {
  home = mkdtempSync(join(tmpdir(), "omb-room-alias-")); vi.resetModules(); vi.stubEnv("HOME", home); vi.stubEnv("USERPROFILE", home);
  const { Store } = await import("./store.ts"); const selection = () => ({ instanceId: "claude", model: "m" }); const store = new Store(selection);
  const a = store.createBot(); const b = store.createBot(); const group = store.createGroup("Room", [a.id,b.id]);
  const first = store.registerRoomRuntimeThread(group.id, group.threadId, a.id);
  const second = store.registerRoomRuntimeThread(group.id, group.threadId, b.id);
  expect(first).not.toBe(second); expect(first).not.toBe(group.threadId);
  store.appendMessage(first, { role: "bot", kind: "text", text: "a", from: { botId:a.id,name:a.name,color:a.color } });
  store.appendMessage(second, { role: "bot", kind: "text", text: "b", from: { botId:b.id,name:b.name,color:b.color } });
  expect(store.messagesFor(group.threadId).map(m=>m.text)).toEqual(["a","b"]);
  expect(store.groupTasks(group.id)).toHaveLength(1);
  store.setRoomActivity(first,a.id,"working"); store.setTaskActivity(a.id,a.threadId,"working"); store.setRoomActivity(first,a.id,"idle"); expect(store.bot(a.id)?.busy).toBe(true);
  const aTurn = store.appendMessage(first, { role:"bot",kind:"text",text:"a turn",turnId:"same-provider-id",from:{botId:a.id,name:a.name,color:a.color} });
  const bTurn = store.appendMessage(second, { role:"bot",kind:"text",text:"b turn",turnId:"same-provider-id",from:{botId:b.id,name:b.name,color:b.color} });
  expect(store.settleTurn(first,"same-provider-id",{ok:true})?.id).toBe(aTurn.id);
  expect(store.messagesFor(second).find(m=>m.id===bTurn.id)?.turnTerminal).toBeUndefined();
  expect(store.settleTurn(second,"same-provider-id",{ok:true})?.id).toBe(bTurn.id);
  const recovered = new Store(selection);
  expect(recovered.canonicalThreadId(first)).toBe(group.threadId); expect(recovered.groupByThread(first)?.id).toBe(group.id);
  expect(recovered.registerRoomRuntimeThread(group.id,group.threadId,a.id)).toBe(first);
  expect(recovered.messagesFor(second).map(m=>m.text)).toEqual(["a","b","a turn","b turn"]);
  expect(recovered.groupTasks(group.id)).toHaveLength(1);
});
